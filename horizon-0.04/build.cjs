'use strict';
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const {createHash} = require('node:crypto');
const read = name => fs.readFileSync(path.join(__dirname, '..', name), 'utf8');
const atlas = fs.readFileSync(path.join(__dirname, '..', 'horizon-056.html'));
const expected = '715c3b41a045d0d62cbbd65893c39f06121c6d8d15013aa166fa4a028f93c8cb';
if (createHash('sha256').update(atlas).digest('hex') !== expected) throw Error('Atlas baseline hash mismatch');
const world = atlas.toString('utf8').match(/<script id="horizonWorld">([\s\S]*?)<\/script>/)?.[1];
const stop = world?.indexOf('const atlasWorldReady=');
if (!(stop > 0)) throw Error('Atlas world script not found');
const worker = read('horizon-0.04/world-worker.js')
 .replace('/* INSERT_FROZEN_ATLAS */', () => world.slice(0, stop)) +
 '\n' + read('horizon-0.04/surface-pattern.js') +
 '\n' + read('horizon-0.02/diagnose-worker.js');
new vm.Script(worker);
fs.writeFileSync(path.join(__dirname, 'world-source.js'),
 '// Generated by node horizon-0.04/build.cjs\nconst HORIZON_WORLD_SOURCE = '+JSON.stringify(worker)+';\n');

